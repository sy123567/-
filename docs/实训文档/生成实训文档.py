def build_meeting_records():
    doc = Document()
    set_base_style(doc)
    for index, meeting in enumerate(MEETINGS):
        if index:
            doc.add_page_break()
        title(doc, "工作讨论记录", 16)
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        p.add_run(f"文件编号：XJYB-MOM-{index + 1:03d}")
        grid(
            doc,
            [
                ["讨论主题", meeting["主题"], "", ""],
                ["讨论地点", meeting["地点"], "讨论时间", meeting["时间"]],
                [
                    "参加人员",
                    "\n".join(f"{name}：{role}" for _, name, role, _ in MEMBERS),
                    "",
                    "",
                ],
                ["会议主持", meeting["主持"], "记录人员", meeting["记录"]],
            ],
            widths=[2.5, 5.5, 2.5, 5.5],
        )
        doc.add_paragraph()
        para(doc, "一、议程", bold=True, indent=False)
        for i, item in enumerate(meeting["议程"], 1):
            para(doc, f"{i}、{item}")
        para(doc, "二、讨论记录", bold=True, indent=False)
        for speaker, topic, points in meeting["讨论"]:
            para(doc, f"{speaker}：{topic}", bold=True, indent=False)
            for i, point in enumerate(points, 1):
                p = doc.add_paragraph()
                p.paragraph_format.left_indent = Pt(28)
                p.add_run(f"{i}. {point}")
        para(doc, "三、总结与执行", bold=True, indent=False)
        para(doc, "参与各方充分讨论，虽存在一些分歧，但达成如下协议：", indent=False)
        for i, item in enumerate(meeting["协议"], 1):
            para(doc, f"{i}、{item}")
        para(doc, f"执行：{meeting['执行']}", indent=False)
    doc.save(os.path.join(OUT, "工作讨论记录-行迹应变.docx"))


